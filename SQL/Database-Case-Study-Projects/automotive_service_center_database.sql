CREATE DATABASE automotive_service_db;
USE automotive_service_db;

DROP TABLE IF EXISTS payments;
DROP TABLE IF EXISTS service_order_items;
DROP TABLE IF EXISTS service_orders;
DROP TABLE IF EXISTS appointments;
DROP TABLE IF EXISTS services;
DROP TABLE IF EXISTS technicians;
DROP TABLE IF EXISTS vehicles;
DROP TABLE IF EXISTS customers;
DROP TABLE IF EXISTS locations;

CREATE TABLE locations (
    location_id INT PRIMARY KEY,
    location_name VARCHAR(100),
    city VARCHAR(100)
);

CREATE TABLE customers (
    customer_id INT PRIMARY KEY,
    first_name VARCHAR(100),
    last_name VARCHAR(100),
    email VARCHAR(255),
    created_at TIMESTAMP
);

CREATE TABLE vehicles (
    vehicle_id INT PRIMARY KEY,
    customer_id INT NOT NULL,
    make VARCHAR(50),
    model VARCHAR(50),
    year INT,
    vehicle_type VARCHAR(30),  -- Sedan, SUV, Truck, Hatchback
    FOREIGN KEY (customer_id) REFERENCES customers(customer_id)
);

CREATE TABLE technicians (
    technician_id INT PRIMARY KEY,
    first_name VARCHAR(100),
    last_name VARCHAR(100),
    location_id INT,
    FOREIGN KEY (location_id) REFERENCES locations(location_id)
);

CREATE TABLE services (
    service_id INT PRIMARY KEY,
    service_name VARCHAR(150),
    category VARCHAR(50),
    price DECIMAL(10,2)
);

CREATE TABLE appointments (
    appointment_id INT PRIMARY KEY,
    customer_id INT NOT NULL,
    vehicle_id INT NOT NULL,
    location_id INT,
    appointment_date TIMESTAMP,
    status VARCHAR(20),   -- Completed, Cancelled, No-show, Scheduled
    FOREIGN KEY (customer_id) REFERENCES customers(customer_id),
    FOREIGN KEY (vehicle_id) REFERENCES vehicles(vehicle_id),
    FOREIGN KEY (location_id) REFERENCES locations(location_id)
);

CREATE TABLE service_orders (
    service_order_id INT PRIMARY KEY,
    appointment_id INT,
    vehicle_id INT NOT NULL,
    technician_id INT,
    location_id INT,
    order_date TIMESTAMP,
    status VARCHAR(20),    -- Open, Completed, Cancelled
    total_amount DECIMAL(10,2),
    FOREIGN KEY (appointment_id) REFERENCES appointments(appointment_id),
    FOREIGN KEY (vehicle_id) REFERENCES vehicles(vehicle_id),
    FOREIGN KEY (technician_id) REFERENCES technicians(technician_id),
    FOREIGN KEY (location_id) REFERENCES locations(location_id)
);

CREATE TABLE service_order_items (
    item_id INT PRIMARY KEY,
    service_order_id INT NOT NULL,
    service_id INT NOT NULL,
    quantity INT,
    price DECIMAL(10,2),
    FOREIGN KEY (service_order_id) REFERENCES service_orders(service_order_id),
    FOREIGN KEY (service_id) REFERENCES services(service_id)
);

CREATE TABLE payments (
    payment_id INT PRIMARY KEY,
    service_order_id INT NOT NULL,
    amount DECIMAL(10,2),
    payment_date TIMESTAMP,
    status VARCHAR(20),
    FOREIGN KEY (service_order_id) REFERENCES service_orders(service_order_id)
);


