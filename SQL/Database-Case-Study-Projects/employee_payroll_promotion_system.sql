CREATE DATABASE employee_payroll_db;
USE employee_payroll_db;

DROP TABLE IF EXISTS performance_reviews;
DROP TABLE IF EXISTS promotions;
DROP TABLE IF EXISTS salary_history;
DROP TABLE IF EXISTS employees;
DROP TABLE IF EXISTS departments;

CREATE TABLE departments (
    department_id INT PRIMARY KEY,
    department_name VARCHAR(100)
);

CREATE TABLE employees (
    employee_id INT PRIMARY KEY,
    first_name VARCHAR(100),
    last_name VARCHAR(100),
    department_id INT,
    manager_id INT,          -- self-referencing FK, NULL for top-level managers
    hire_date DATE,
    status VARCHAR(20),      -- Active, Terminated
    FOREIGN KEY (department_id) REFERENCES departments(department_id),
    FOREIGN KEY (manager_id) REFERENCES employees(employee_id)
);

CREATE TABLE salary_history (
    salary_id INT PRIMARY KEY,
    employee_id INT NOT NULL,
    salary DECIMAL(12,2),
    effective_date DATE,
    FOREIGN KEY (employee_id) REFERENCES employees(employee_id)
);

CREATE TABLE promotions (
    promotion_id INT PRIMARY KEY,
    employee_id INT NOT NULL,
    promotion_date DATE,
    old_title VARCHAR(100),
    new_title VARCHAR(100),
    FOREIGN KEY (employee_id) REFERENCES employees(employee_id)
);

CREATE TABLE performance_reviews (
    review_id INT PRIMARY KEY,
    employee_id INT NOT NULL,
    review_date DATE,
    score DECIMAL(3,1),      -- 1.0 to 5.0
    comments VARCHAR(300),
    FOREIGN KEY (employee_id) REFERENCES employees(employee_id)
);


